HEADER = "<!-- generated by batch_extract_with_claude.py via pdfplumber -->\n"


def _line(tokens, top=100.0):
    """tokens: [(text, x0, size)] or [(text, x0, size, top)] -> one extract_text_lines line.
    Chars carry no space characters (the token geometry check joins tokens without spaces)."""
    chars, toks = [], []
    for t in tokens:
        text, x0, size = t[:3]
        tp = t[3] if len(t) > 3 else top
        toks.append(text)
        for i, c in enumerate(text):
            w = size * 0.5
            chars.append({"text": c, "x0": x0 + i * w, "x1": x0 + (i + 1) * w, "top": tp, "size": size})
    return {"text": " ".join(toks), "chars": chars}


class _Page:
    def __init__(self, lines, text=None, number=1):
        self._lines, self._text, self.page_number = lines, text, number

    def extract_text_lines(self, return_chars=False, strip=True):
        assert return_chars and not strip
        return self._lines

    def extract_text(self):
        return self._text if self._text is not None else "\n".join(ln["text"] for ln in self._lines)


def _host_sub(host, sub, host_size=10, sub_size=6):
    """one line: host token, then a small sub token touching it, plus a normal-size filler so the
    line median stays at the host size."""
    hw = len(host) * host_size * 0.5
    return _line([(host, 0, host_size), (sub, hw, sub_size), ("filler", hw + 40, host_size)])


def _glue(lines, **kw):
    log = {}
    return ei._glue_page(_Page(lines), log=log, **kw), log.get("r1", [])


def test_r1_merges_small_same_line_token():
    text, log = _glue([_host_sub("V", "DD")])
    assert text == "VDD filler"
    assert log[0]["outcome"] == "kept" and log[0]["host"] == "V" and log[0]["sub"] == "DD"
    assert log[0]["page"] == 1


def test_r2_merges_subscript_line_onto_line_above():
    above = _line([("V", 0, 10, 100.0), ("min", 20, 10, 100.0)])
    sub = _line([("IH", 5, 6, 104.0)], top=104.0)
    text, _ = _glue([above, sub])
    assert text == "VIH min"


def test_x1_no_merge_onto_pure_number_host():
    text, log = _glue([_host_sub("3", "V")])
    assert text == "3 V filler" and log[0]["outcome"] == "blocked_x1"
    above = _line([("3", 0, 10, 100.0)])
    sub = _line([("V", 5, 6, 104.0)], top=104.0)
    assert _glue([above, sub])[0] == "3\nV"            # R2 too


def test_x2_no_digit_led_sub_onto_host_ending_in_digit_or_dot():
    text, log = _glue([_host_sub("A1", "2")])
    assert text == "A1 2 filler" and log[0]["outcome"] == "blocked_x2"
    text, log = _glue([_host_sub("Pin.", "5")])
    assert log[0]["outcome"] == "blocked_x2"


def test_x3_r1_off_near_figure():
    lines = [_line([("Figure", 0, 10), ("1.", 40, 10)]), _host_sub("V", "DD")]
    text, log = _glue(lines)
    assert text.split("\n")[1] == "V DD filler" and log[0]["outcome"] == "blocked_x3"
    far = [_line([("x", 0, 10)])] * 4
    far = [_line([("Figure", 0, 10)])] + far + [_host_sub("V", "DD")]
    assert _glue(far)[0].split("\n")[-1] == "VDD filler"


@pytest.mark.parametrize("sub", ["ab", "ABCDE", "A_B"])
def test_x4a_only_short_uppercase_alnum_subs_merge(sub):
    text, log = _glue([_host_sub("V", sub)])
    assert text == f"V {sub} filler" and log[0]["outcome"] == "blocked_x4"


def test_x4b_host_must_start_with_a_letter():
    text, log = _glue([_host_sub("15V", "IN")])
    assert text == "15V IN filler" and log[0]["outcome"] == "blocked_x4"
    text, log = _glue([_host_sub("+V", "A")])
    assert text == "+VA filler" and log[0]["outcome"] == "kept"


def test_x4_off_restores_v3_g_behaviour():
    text, log = _glue([_host_sub("15V", "IN")], x4=False)
    assert text == "15VIN filler" and log[0]["outcome"] == "kept"


def test_page_without_geometry_takes_no_merge():
    ln = {"text": "ab cd", "chars": [{"text": "x", "x0": 0, "x1": 1, "top": 0, "size": 10}]}
    assert ei._glue_page(_Page([ln])) == "ab cd"


class _Doc:
    def __init__(self, pages):
        self.pages = pages

    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False


def _fake_pdfplumber(monkeypatch, pages):
    import types
    mod = types.ModuleType("pdfplumber")
    mod.open = lambda p: _Doc(pages)
    monkeypatch.setitem(sys.modules, "pdfplumber", mod)


def test_glue_version_0_uses_extract_text_and_ignores_lines_api(monkeypatch):
    class Plain:
        def extract_text(self):
            return "VDD plain"

        def extract_text_lines(self, **kw):
            raise AssertionError("lines API must not be used at GLUE_VERSION 0")
    _fake_pdfplumber(monkeypatch, [Plain()])
    monkeypatch.setattr(ei, "GLUE_VERSION", 0)
    assert ei.extract_pdfplumber_full(Path("x.pdf")) == HEADER + "\n<!-- page 1 -->\nVDD plain"


def test_extract_pdfplumber_full_framing_with_glue(monkeypatch):
    p1 = _Page([_host_sub("V", "DD")])
    blank = _Page([], text="")
    p3 = _Page([_line([("hello", 0, 10)])])
    _fake_pdfplumber(monkeypatch, [p1, blank, p3])
    assert ei.GLUE_VERSION >= 1
    out = ei.extract_pdfplumber_full(Path("x.pdf"))
    assert out == HEADER + "\n<!-- page 1 -->\nVDD filler" + "\n" + "\n<!-- page 3 -->\nhello"


